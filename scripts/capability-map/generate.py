# ----------------------------------------------------------- heat map page
def impl_heat_diagram(l1s):
    lines = ["```mermaid", INIT, "flowchart TB"]
    for l1 in l1s:
        lines.append(f'    subgraph S{l1["id"]}["{l1["id"]} {wrap(l1["name"], 18)}"]')
        lines.append("        direction TB")
        ids = []
        for l2 in l1["l2"]:
            nid = "H" + l2["id"].replace(".", "_")
            ids.append(nid)
            lines.append(f'        {nid}["{l2["id"]} {wrap(l2["name"], 18)}"]')
        for g_i, g in enumerate([g for g in cm.GAPS if g["l1"] == l1["name"]]):
            nid = f"G{l1['id']}_{g_i}"
            ids.append(nid)
            lines.append(f'        {nid}["gap: {wrap(g["name"], 16)}"]')
        for a, b in zip(ids, ids[1:]):
            lines.append(f"        {a} ~~~ {b}")
        lines.append("    end")
    for l1 in l1s:
        for l2 in l1["l2"]:
            nid = "H" + l2["id"].replace(".", "_")
            lines.append(f"    class {nid} {'partial' if l2_status(l2) == 'Partial' else 'impl'}")
        for g_i, g in enumerate([g for g in cm.GAPS if g["l1"] == l1["name"]]):
            lines.append(f"    class G{l1['id']}_{g_i} gap")
    lines += CLASSDEFS
    lines.append("```")
    return "\n".join(lines)


