def l1_map_diagram():
    lines = ["```mermaid", INIT, "flowchart TB"]
    prev = None
    for tier in cm.TIERS:
        tid = f"T{tier[:3].upper()}"
        lines.append(f'    subgraph {tid}["{tier} tier - {cm.TIER_FOCUS[tier]}"]')
        lines.append("        direction TB")
        l1s = [l1 for l1 in M if l1["tier"] == tier]
        for l1 in l1s:
            label = f"<b>{l1['id']} {wrap(l1['name'], 22)}</b><br/>{len(l1['l2'])} L2, {sum(len(x['l3']) for x in l1['l2'])} L3"
            lines.append(f'        C{l1["id"]}["{label}"]')
        # rows of four: link item i to item i+4 invisibly to stack rows
        for a, b in zip(l1s, l1s[4:]):
            lines.append(f"        C{a['id']} ~~~ C{b['id']}")
        lines.append("    end")
        if prev:
            lines.append(f"    {prev} ~~~ {tid}")
        prev = tid
    for l1 in M:
        lines.append(f"    class C{l1['id']} {TIER_CLASS[l1['tier']]}")
    lines += CLASSDEFS
    lines.append("```")
    return "\n".join(lines)


def l1_detail_diagram(l1):
    lines = ["```mermaid", INIT, "flowchart LR"]
    lines.append(f'    L1["<b>L1 {l1["id"]}</b><br/>{wrap(l1["name"], 20)}"]')
    for l2 in l1["l2"]:
        body = "<br/>".join(f"{x['id']} {x['name']}" for x in l2["l3"])
        nid = "N" + l2["id"].replace(".", "_")
        lines.append(f'    {nid}["<b>L2 {l2["id"]} {l2["name"]}</b><br/>{body}"]')
        lines.append(f"    L1 --> {nid}")
        cls = "partial" if l2_status(l2) == "Partial" else "impl"
        lines.append(f"    class {nid} {cls}")
    lines.append(f"    class L1 {TIER_CLASS[l1['tier']]}")
    lines += CLASSDEFS
    lines.append("```")
    return "\n".join(lines)


