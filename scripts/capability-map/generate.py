def validate_model():
    names = set()
    for l1 in M:
        assert l1["tier"] in cm.TIERS, l1["name"]
        for l2 in l1["l2"]:
            for x in l2["l3"]:
                assert x["desc"].startswith("The ability to"), x["name"]
                assert x["evidence"], x["name"]
                for c in x["ctxs"]:
                    assert c in CODE, (x["name"], c)
            for n in [l2["name"]] + [x["name"] for x in l2["l3"]]:
                assert n not in names or n == l2["name"], f"duplicate capability name {n}"
            names.update(x["name"] for x in l2["l3"])
        assert l1["desc"].startswith("The ability to"), l1["name"]
    for vs in cm.VALUE_STREAMS:
        for _, caps in vs["stages"]:
            for c in caps:
                assert c in L2_BY_NAME, (vs["name"], c)
    for g in cm.GAPS:
        assert g["l1"] is None or g["l1"] in L1_BY_NAME, g["name"]


def main():
    validate_model()
    check = "--check" in sys.argv
    stale = []
    OUT.mkdir(parents=True, exist_ok=True)
    for fname, fn in PAGES.items():
        text = fn()
        path = OUT / fname
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(fname)
        else:
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("stale generated pages: " + ", ".join(stale))
        sys.exit(1)


if __name__ == "__main__":
    main()
