DDD = {name: cls for name, _, cls in cm.CONTEXTS}


def wrap(s, width):
    return "<br/>".join(textwrap.wrap(s, width, break_on_hyphens=False))


def l1_contexts(l1):
    seen = []
    for l2 in l1["l2"]:
        for x in l2["l3"]:
            for c in x["ctxs"]:
                if c not in seen:
                    seen.append(c)
    return seen


def l2_contexts(l2):
    seen = []
    for x in l2["l3"]:
        for c in x["ctxs"]:
            if c not in seen:
                seen.append(c)
    return seen


def l2_status(l2):
    st = {x["status"] for x in l2["l3"]}
    return "Partial" if "Partial" in st else "Implemented"


def ctx_links(ctxs):
    return ", ".join(f"[{c}](/contexts/{c})" for c in ctxs)


def cited(text):
    """Citation ids used in the page body, code fences excluded."""
    import re
    body = re.sub(r"```.*?```", "", text, flags=re.S)
    return sorted({int(n) for n in re.findall(r"\[(\d{1,2})\]", body)})


def sources_block(ids):
    lines = ["## Sources", ""]
    for i in sorted(ids):
        title, url = SOURCES[i]
        lines.append(f"- **[{i}]** [{title}]({url})")
    return "\n".join(lines) + "\n"


def yq(s):
    """Double-quoted YAML scalar (titles and descriptions contain colons)."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def frontmatter(pid, title, label, desc):
    return f"---\nid: {pid}\ntitle: {yq(title)}\nsidebar_label: {yq(label)}\ndescription: {yq(desc)}\n---\n\n# {title}\n\n"


