# ----------------------------------------------------------------- numbering
def numbered():
    """Attach ids: L1 n, L2 n.m, L3 n.m.k."""
    out = []
    for i, l1 in enumerate(cm.MODEL, 1):
        l1 = dict(l1, id=str(i))
        l2s = []
        for j, l2 in enumerate(l1["l2"], 1):
            l2 = dict(l2, id=f"{i}.{j}")
            l2["l3"] = [dict(x, id=f"{i}.{j}.{k}") for k, x in enumerate(l2["l3"], 1)]
            l2s.append(l2)
        l1["l2"] = l2s
        out.append(l1)
    return out


M = numbered()
L2_BY_NAME = {l2["name"]: l2 for l1 in M for l2 in l1["l2"]}
L1_BY_NAME = {l1["name"]: l1 for l1 in M}
