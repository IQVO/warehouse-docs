import type {SidebarsConfig} from '@docusaurus/plugin-content-docs';

/**
 * Storefront docs instance sidebars. Every context carries its 14-page
 * ddd-crew pack (one category each below). storefront-bff, storefront-web and
 * payment-provider-simulator are not bounded contexts: they share the
 * `components` page, and every repo's ADRs are indexed on `adr/index`.
 */
const CONTEXTS = [
  'pricing',
  'product-content',
  'product-discovery',
  'shopping-cart',
  'checkout',
  'customer-payments',
];

/**
 * Contexts whose ddd-crew pack exists under contexts/<ctx>/. Every pack
 * lists the same page set, in the same order, so contexts can be compared
 * page for page.
 */
const PACK_CONTEXTS = [
  'pricing',
  'product-content',
  'product-discovery',
  'shopping-cart',
  'checkout',
  'customer-payments',
];

/** ddd-crew pack page set, same order as the network packs. */
const CONTEXT_PAGES = [
  'business-context',
  'ubiquitous-language',
  'core-domain-chart',
  'bounded-context-canvas',
  'context-map',
  'aggregate-design-canvas',
  'domain-events',
  'domain-message-flow',
  'eventstorming',
  'use-cases',
  'class-diagram',
  'entity-relationship',
  'sequence-diagrams',
];

const contextCategories = PACK_CONTEXTS.map((ctx) => ({
  type: 'category' as const,
  label: ctx,
  link: {type: 'doc' as const, id: `contexts/${ctx}/index`},
  items: CONTEXT_PAGES.map((p) => `contexts/${ctx}/${p}`),
}));

const apiCategories = CONTEXTS.map((ctx) => ({
  type: 'category' as const,
  label: ctx,
  items: [{type: 'autogenerated' as const, dirName: `api-reference/rest/${ctx}`}],
}));

const sidebars: SidebarsConfig = {
  strategicSidebar: [
    'overview',
    'components',
    'adr/index',
    {
      type: 'category',
      label: 'Strategic Design',
      link: {type: 'doc', id: 'strategic-design/index'},
      items: [
        'strategic-design/subdomain-classification',
        'strategic-design/context-map',
        'strategic-design/ubiquitous-language',
        'strategic-design/event-standard-cloudevents',
        'strategic-design/model-gap-register',
      ],
    },
    {
      type: 'category',
      label: 'Research',
      items: ['research/benchmarks'],
    },
  ],
  contextsSidebar: ['contexts/index', ...contextCategories],
  apiSidebar: [
    'api-reference/index',
    ...apiCategories,
    {
      type: 'category',
      label: 'storefront-bff (edge)',
      items: [{type: 'autogenerated', dirName: 'api-reference/rest/storefront-bff'}],
    },
  ],
};

export default sidebars;
